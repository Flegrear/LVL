function ffmpeg(parameters) {
  const child = spawnSync(ffmpegPath, ["-hide_banner", "-loglevel", "error", "-nostdin", ...parameters],
    { windowsHide: true, timeout: 25_000, encoding: "utf8", maxBuffer: 3_000_000 });
  assert.equal(child.status, 0, child.stderr || child.error?.message || "FFmpeg failed");
  return child.stdout;
}
function firstFrameHash(file, from = null) {
  const text = ffmpeg([
    ...(from === null ? [] : ["-ss", String(from)]),
    "-i", file, "-map", "0:v:0", "-frames:v", "1", "-pix_fmt", "yuv420p", "-f", "framemd5", "-",
  ]);
  const frame = text.split(/\r?\n/).find((line) => /^0,/.test(line));
  assert.ok(frame, "Synthetic decoded frame hash exists");
  return frame.split(",").at(-1).trim();
}

